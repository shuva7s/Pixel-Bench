#!/usr/bin/env node
// Generates out/sw.js: a service worker that makes the static site work
// offline. Core files are pre-cached on the first visit; codecs that are only
// needed for some formats (AVIF, lossy WebP, HEIC) are cached when first used.
import { createHash } from "node:crypto";
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join, relative, sep } from "node:path";
import { fileURLToPath } from "node:url";

const out = fileURLToPath(new URL("../out", import.meta.url));
const base = process.env.NEXT_PUBLIC_BASE_PATH ?? "";

/** Files fetched on demand: cached at runtime instead of up front. */
const LAZY = [
  /avif_encoder_bg\..*\.wasm$/,
  /webp_enc(_simd)?\..*\.wasm$/,
  /vendor\/libheif\.wasm$/,
  /^vendor\/ort\//,
  /^models\//,
  /\.map$/,
];

function walk(dir, files = []) {
  for (const name of readdirSync(dir)) {
    const full = join(dir, name);
    if (statSync(full).isDirectory()) walk(full, files);
    else files.push(full);
  }
  return files;
}

const hash = createHash("sha256");
const core = [];
for (const full of walk(out).sort()) {
  const rel = relative(out, full).split(sep).join("/");
  if (rel === "sw.js") continue;
  hash.update(rel);
  hash.update(readFileSync(full));
  if (LAZY.some((re) => re.test(rel))) continue;
  // Pages are cached by their directory URL (trailingSlash: true).
  const url = rel.endsWith("index.html") ? `${base}/${rel.slice(0, -"index.html".length)}` : `${base}/${rel}`;
  core.push(url);
}
const version = hash.digest("hex").slice(0, 12);

const sw = `// Generated by scripts/build-sw.mjs — do not edit.
const VERSION = ${JSON.stringify(version)};
const CACHE = "pixel-bench-" + VERSION;
const CORE = ${JSON.stringify(core)};

self.addEventListener("install", (event) => {
  event.waitUntil(caches.open(CACHE).then((c) => c.addAll(CORE)).then(() => self.skipWaiting()));
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches
      .keys()
      // Remove old app versions; keep downloaded AI models.
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith("pixel-bench-") && k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener("fetch", (event) => {
  const req = event.request;
  const url = new URL(req.url);
  if (req.method !== "GET" || url.origin !== self.location.origin) return;
  // AI models are verified and cached by the app itself (Cache "models-v1"), which survives updates.
  if (/\\/models\\/[^/]+\\.onnx$/.test(url.pathname)) return;
  if (req.mode === "navigate") {
    // Pages: network first so updates show up; cached copy when offline.
    event.respondWith(
      fetch(req)
        .then((res) => {
          const copy = res.clone();
          if (res.ok) caches.open(CACHE).then((c) => c.put(req, copy));
          return res;
        })
        .catch(async () => (await caches.match(req, { ignoreSearch: true })) ?? (await caches.match(${JSON.stringify(base + "/")}))),
    );
    return;
  }
  if (req.destination === "worker" || req.destination === "sharedworker") {
    // Worker bootstrap config travels in the script URL's query string, and a
    // worker takes its location from the response URL. Look the script up
    // without the query, then re-wrap it so the worker sees the request URL.
    event.respondWith(
      caches.match(req, { ignoreSearch: true }).then(async (hit) => {
        if (!hit) return fetch(req);
        return new Response(await hit.blob(), { status: hit.status, statusText: hit.statusText, headers: hit.headers });
      }),
    );
    return;
  }
  // Assets are content-hashed: cache first, then network (and remember it).
  event.respondWith(
    caches.match(req, { ignoreSearch: url.pathname.endsWith(".txt") }).then(
      (hit) =>
        hit ??
        fetch(req).then((res) => {
          if (res.ok) {
            const copy = res.clone();
            caches.open(CACHE).then((c) => c.put(req, copy));
          }
          return res;
        }),
    ),
  );
});
`;
writeFileSync(join(out, "sw.js"), sw);
console.log(`build-sw: ${core.length} files pre-cached, version ${version}`);
